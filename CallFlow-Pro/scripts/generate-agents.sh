#!/usr/bin/env bash
# =============================================================
# CallFlow Pro - Bulk Agent Provisioning Script (chan_sip)
# Generates 200 SIP peers + agents.conf entries +
# voicemail boxes from a single range definition.
#
# Usage: ./generate-agents.sh
# Output:
#   configs/agents-sip.conf       (included from sip.conf)
#   configs/agents-generated.conf
#   configs/voicemail-generated.conf
# =============================================================
set -euo pipefail

OUT_DIR="$(cd "$(dirname "$0")/../configs" && pwd)"
SIP_OUT="${OUT_DIR}/agents-sip.conf"
AGENTS_OUT="${OUT_DIR}/agents-generated.conf"
VM_OUT="${OUT_DIR}/voicemail-generated.conf"

# team_name:start_ext:end_ext:context
TEAMS=(
    "sales:6001:6050:agents-sales"
    "support:6101:6150:agents-support"
    "billing:6201:6220:agents-billing"
    "floating:6301:6310:agents-floating"
)

random_password() {
    tr -dc 'A-Za-z0-9' </dev/urandom | head -c 16
}

random_pin() {
    printf "%04d" $((RANDOM % 10000))
}

: > "$SIP_OUT"
: > "$AGENTS_OUT"
: > "$VM_OUT"

echo "; Auto-generated by generate-agents.sh on $(date)" >> "$SIP_OUT"
echo "; Auto-generated by generate-agents.sh on $(date)" >> "$AGENTS_OUT"
echo "; Auto-generated by generate-agents.sh on $(date)" >> "$VM_OUT"

for team_def in "${TEAMS[@]}"; do
    IFS=':' read -r team start end context <<< "$team_def"
    echo "Generating agents for team [$team]: ${start}-${end}"

    for ((ext=start; ext<=end; ext++)); do
        pass="$(random_password)"
        pin="$(random_pin)"

        cat >> "$SIP_OUT" <<EOF

[${ext}](agent-template)
secret=${pass}
context=${context}
callerid="Agent ${ext} <${ext}>"
mailbox=${ext}@${team}
EOF

        echo "${ext} => ${pin},Agent ${ext},${team}" >> "$AGENTS_OUT"
        echo "${ext} => ${pin},Agent ${ext},agent${ext}@callflowpro.com,,attach=yes|saycid=yes" >> "$VM_OUT"
    done
done

echo ""
echo "Done. Generated files:"
echo "  - ${SIP_OUT}"
echo "  - ${AGENTS_OUT}"
echo "  - ${VM_OUT}"
echo ""
echo "IMPORTANT: Passwords/PINs were randomly generated."
echo "Store them securely (e.g. HashiCorp Vault) before distributing to agents."
